// Builds supabase/seed/mock_marketplace.sql: the Preview (is_mock) marketplace used to try SajuTeller.
//
//   node scripts/generate-mock-seed.mjs
//   supabase db query --linked -f supabase/seed/mock_marketplace.sql   (CLI >= 2.9x)
//
// The SQL runs in one transaction. It deletes every is_mock studio (and its services, readers, slots, images,
// reviews) and every is_mock profile, then inserts the studios from scripts/mock-data. Studios with keepSlug are
// updated in place (matched by old or current slug) so their ids and existing demo chat conversations survive. Real (is_mock = false) rows
// are never touched. Output is deterministic: same input, same SQL.
import { writeFileSync } from 'node:fs';
import { areas, hours, photos, services, tiers } from './mock-data/catalog.mjs';
import partA from './mock-data/studios-a.mjs';
import partB from './mock-data/studios-b.mjs';
import { pools, travellers } from './mock-data/reviews.mjs';

const studios = [...partA, ...partB];

let seed = 20261024;
const rand = () => { seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const pick = a => a[Math.floor(rand() * a.length)];
const int = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));
const shuffle = a => { const b = [...a]; for (let i = b.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [b[i], b[j]] = [b[j], b[i]]; } return b; };

const q = s => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const j = o => `${q(JSON.stringify(o))}::jsonb`;
const arr = a => `array[${a.map(q).join(',')}]::text[]`;
const sid = slug => `(select id from public.saju_studios where slug=${q(slug)})`;
const round5k = n => Math.max(5000, Math.round(n / 5000) * 5000);

// ---- validation -------------------------------------------------------------------------------------------
const seen = new Set();
for (const s of studios) {
  if (seen.has(s.slug)) throw new Error(`duplicate slug ${s.slug}`);
  seen.add(s.slug);
  if (!areas[s.area]) throw new Error(`${s.slug}: unknown area ${s.area}`);
  if (!hours[s.hours]) throw new Error(`${s.slug}: unknown hours ${s.hours}`);
  for (const k of s.services) if (!services[k]) throw new Error(`${s.slug}: unknown service ${k}`);
  for (const p of s.photos) if (!photos[p]) throw new Error(`${s.slug}: unknown photo ${p}`);
  for (const pair of s.langs.split(' ')) if (!/^(ko|en|zh|ja|es):(native|conversational|interpreter|ai_interpreter)$/.test(pair)) throw new Error(`${s.slug}: bad language ${pair}`);
  for (const f of ['tag', 'desc']) for (const l of ['en', 'ko', 'zh', 'ja', 'es']) if (!s[f][l]) throw new Error(`${s.slug}: missing ${f}.${l}`);
}
if (studios.length < 30) throw new Error('need at least 30 studios');
const travellerName = ([first, last]) => `${first} ${last[0]}.`;
if (new Set(travellers.map(travellerName)).size !== travellers.length) throw new Error('duplicate traveller display names');

// ---- SQL ---------------------------------------------------------------------------------------------------
const out = [];
const w = s => out.push(s);
const keep = studios.filter(s => s.keepSlug);

w(`-- Generated by scripts/generate-mock-seed.mjs. Do not edit by hand.
-- Preview marketplace: ${studios.length} sample studios (is_mock = true). Real studios and users are untouched.
begin;

-- 1. Remove existing mock data. Studios kept by id lose their children and are rewritten below.
-- Demo requests point at mock services, so they go first.
delete from public.sajuteller_booking_requests where studio_id in (select id from public.saju_studios where is_mock);
delete from public.saju_studios where is_mock and slug not in (${keep.flatMap(s => [q(s.keepSlug), q(s.slug)]).join(',')});
delete from public.studio_availability_slots where studio_id in (select id from public.saju_studios where is_mock);
delete from public.studio_reviews where studio_id in (select id from public.saju_studios where is_mock);
delete from public.studio_images where studio_id in (select id from public.saju_studios where is_mock);
delete from public.studio_services where studio_id in (select id from public.saju_studios where is_mock);
delete from public.studio_practitioners where studio_id in (select id from public.saju_studios where is_mock);
delete from public.studio_languages where studio_id in (select id from public.saju_studios where is_mock);
delete from public.studio_hours where studio_id in (select id from public.saju_studios where is_mock);
delete from public.profiles where is_mock;
`);

// 2. Studios
const cols = ['slug', 'name', 'name_ko', 'tagline', 'tagline_i18n', 'description', 'description_i18n', 'status', 'is_mock', 'demo_chat_enabled', 'is_featured', 'verified', 'verification_note',
  'address_line1', 'city', 'district', 'neighborhood', 'latitude', 'longitude', 'nearest_station', 'station_walk_minutes', 'base_price', 'currency', 'min_duration_minutes', 'max_guests', 'min_age',
  'specialties', 'modalities', 'ai_interpretation_available', 'wheelchair_accessible', 'walk_ins', 'instant_book', 'phone', 'email', 'website'];
const areaCount = {};
w('-- 2. Studios');
for (const s of studios) {
  const a = areas[s.area];
  const n = areaCount[s.area] = (areaCount[s.area] || 0) + 1;
  // Spread studios in the same neighbourhood around its centre (~150–350 m) so map pins don't stack.
  const angle = n * 2.4 + rand() * 0.6, dist = 0.0013 + rand() * 0.0017;
  const lat = +(a.lat + Math.sin(angle) * dist).toFixed(6), lng = +(a.lng + Math.cos(angle) * dist * 1.25).toFixed(6);
  const svc = s.services.map(k => services[k]);
  const prices = svc.map(t => round5k(t[2] * tiers[s.tier]));
  s._prices = prices;
  const values = [q(s.slug), q(s.name), q(s.ko), q(s.tag.en), j(s.tag), q(s.desc.en), j(s.desc), q('active'), 'true', 'true', s.featured ? 'true' : 'false', 'false',
    q('Preview sample for trying SajuTeller. Not a real business.'),
    q(`Illustrative location · ${a.street}, ${a.district}`), q('Seoul'), q(a.district), q(s.area), lat, lng, q(a.station), s.walk,
    Math.min(...prices), q('KRW'), Math.min(...svc.map(t => t[1])), Math.max(s.guests || 1, ...svc.map(t => t[3])), 0,
    arr(s.specialties), arr(s.modalities), s.ai ? 'true' : 'false', s.wheel ? 'true' : 'false', s.walkIns ? 'true' : 'false', 'false', 'null', 'null', 'null'];
  if (s.keepSlug) {
    w(`update public.saju_studios set (${cols.join(',')}, updated_at) = (${values.join(',')}, now()) where slug in (${q(s.keepSlug)},${q(s.slug)}) and is_mock;`);
  } else {
    w(`insert into public.saju_studios (${cols.join(',')}) values (${values.join(',')});`);
  }
}

// 3. Readers, services, languages, hours, images
w('\n-- 3. Readers, services, languages, hours, photos');
for (const s of studios) {
  const id = sid(s.slug);
  s.readers.forEach(([en, ko, title, bio, bioKo, years, langs], i) => {
    w(`insert into public.studio_practitioners (studio_id,display_name,display_name_ko,title,bio,bio_i18n,languages,specialties,years_experience,is_primary,is_active,verified,sort_order) values (${id},${q(en)},${q(ko)},${q(title)},${q(bio)},${j({ en: bio, ko: bioKo })},${arr(langs)},${arr(s.specialties)},${years},${i === 0},true,false,${i});`);
  });
  s.services.forEach((k, i) => {
    const [type, mins, , guests, birthReq, timeRec, names, descs] = services[k];
    // With two readers, the last service goes to the second one.
    const reader = s.readers.length > 1 && i === s.services.length - 1 ? s.readers[1][0] : s.readers[0][0];
    w(`insert into public.studio_services (studio_id,practitioner_id,service_type,name,name_i18n,description,description_i18n,duration_minutes,price,currency,max_guests,requires_birth_date,birth_time_recommended,sort_order,active) values (${id},(select id from public.studio_practitioners where studio_id=${id} and display_name=${q(reader)}),${q(type)},${q(names.en)},${j(names)},${q(descs.en)},${j(descs)},${mins},${s._prices[i]},'KRW',${guests},${birthReq},${timeRec},${i},true);`);
  });
  w(`insert into public.studio_languages (studio_id,language_code,support_type) values ${s.langs.split(' ').map(p => { const [c, t] = p.split(':'); return `(${id},${q(c)},${q(t)})`; }).join(',')};`);
  w(`insert into public.studio_hours (studio_id,day_of_week,opens_at,closes_at,is_closed) values ${hours[s.hours].map((h, d) => h ? `(${id},${d},${q(h[0])},${q(h[1])},false)` : `(${id},${d},null,null,true)`).join(',')};`);
  w(`insert into public.studio_images (studio_id,image_url,alt_text,image_type,sort_order) values ${s.photos.map((p, i) => `(${id},${q(`https://images.unsplash.com/${photos[p][0]}?auto=format&fit=crop&w=1400&q=82`)},${q(photos[p][1])},${q(i === 0 ? 'cover' : 'interior')},${i})`).join(',')};`);
}

// 4. Mock travellers (profiles without auth accounts) with birth details and preferences
w('\n-- 4. Mock travellers');
const tz = { US: 'America/New_York', CA: 'America/Toronto', GB: 'Europe/London', IE: 'Europe/Dublin', AU: 'Australia/Sydney', NZ: 'Pacific/Auckland', SG: 'Asia/Singapore', MY: 'Asia/Kuala_Lumpur', PH: 'Asia/Manila', DE: 'Europe/Berlin', FR: 'Europe/Paris', IT: 'Europe/Rome', NL: 'Europe/Amsterdam', SE: 'Europe/Stockholm', IN: 'Asia/Kolkata', JP: 'Asia/Tokyo', CN: 'Asia/Shanghai', TW: 'Asia/Taipei', HK: 'Asia/Hong_Kong', MX: 'America/Mexico_City', ES: 'Europe/Madrid', CL: 'America/Santiago', AR: 'America/Argentina/Buenos_Aires', CO: 'America/Bogota', PE: 'America/Lima', KR: 'Asia/Seoul' };
const city = { US: 'New York', CA: 'Toronto', GB: 'London', IE: 'Dublin', AU: 'Sydney', NZ: 'Auckland', SG: 'Singapore', MY: 'Kuala Lumpur', PH: 'Manila', DE: 'Berlin', FR: 'Paris', IT: 'Milan', NL: 'Amsterdam', SE: 'Stockholm', IN: 'Mumbai', JP: 'Tokyo', CN: 'Shanghai', TW: 'Taipei', HK: 'Hong Kong', MX: 'Mexico City', ES: 'Madrid', CL: 'Santiago', AR: 'Buenos Aires', CO: 'Bogotá', PE: 'Lima', KR: 'Busan' };
const currency = { US: 'USD', CA: 'CAD', GB: 'GBP', IE: 'EUR', AU: 'AUD', NZ: 'NZD', SG: 'SGD', MY: 'MYR', PH: 'PHP', DE: 'EUR', FR: 'EUR', IT: 'EUR', NL: 'EUR', SE: 'SEK', IN: 'INR', JP: 'JPY', CN: 'CNY', TW: 'TWD', HK: 'HKD', MX: 'MXN', ES: 'EUR', CL: 'CLP', AR: 'ARS', CO: 'COP', PE: 'PEN', KR: 'KRW' };
const topicSets = [['love', 'compatibility'], ['career', 'wealth'], ['general'], ['love'], ['career'], ['general', 'year_ahead']];
for (const t of travellers) {
  const [first, last, country, lang] = t;
  const name = travellerName(t);
  const born = new Date(Date.UTC(1972 + int(0, 31), int(0, 11), int(1, 28)));
  const unknownTime = rand() < 0.2;
  w(`with p as (insert into public.profiles (display_name,first_name,last_name,country_code,preferred_language,role,onboarding_completed,is_mock) values (${q(name)},${q(first)},${q(last)},${q(country)},${q(lang)},'traveler',true,true) returning id),
 b as (insert into public.user_birth_profiles (user_id,label,relationship,birth_date,birth_time,birth_time_unknown,birth_timezone,birth_country_code,birth_city,gender,is_primary) select id,'Me','self',${q(born.toISOString().slice(0, 10))},${unknownTime ? 'null' : q(`${String(int(0, 23)).padStart(2, '0')}:${pick(['00', '15', '30', '45'])}`)},${unknownTime},${q(tz[country])},${q(country)},${q(city[country])},${q(pick(['female', 'male', 'female', 'male', 'unspecified']))},true from p)
 insert into public.user_preferences (user_id,preferred_currency,preferred_topics,preferred_modalities,preferred_neighborhoods,needs_interpretation) select id,${q(currency[country])},${arr(pick(topicSets))},${arr(rand() < 0.3 ? ['saju', 'tarot'] : ['saju'])},${arr([pick(Object.keys(areas))])},${lang !== 'ko'} from p;`);
}

// 5. Reviews (is_mock; hidden in the app, kept for testing review features)
w('\n-- 5. Reviews');
const ratingFor = () => { const r = rand(); return r < 0.55 ? 5 : r < 0.86 ? 4 : r < 0.96 ? 3 : 2; };
const langWeights = ['en', 'en', 'en', 'en', 'en', 'ja', 'ja', 'zh', 'zh', 'es', 'ko'];
const start = Date.UTC(2026, 1, 1), end = Date.UTC(2026, 9, 18);
let reviewTotal = 0;
for (const s of studios) {
  const id = sid(s.slug);
  const kind = s.modalities[0] === 'tarot' ? 'tarot' : s.services.includes('couple') || s.services.includes('friends') ? 'couple' : 'saju';
  const count = s.featured ? int(14, 24) : int(3, 18);
  const used = new Set();
  const reviewed = new Set();
  const reader = s.readers[0][0].split(' ')[0];
  for (let i = 0; i < count; i++) {
    const rating = ratingFor();
    let lang = pick(langWeights);
    // Readers who speak the guest's language attract more of those guests.
    if (rand() < 0.35) { const spoken = s.readers[0][6].filter(l => l !== 'ko'); if (spoken.length) lang = pick(spoken); }
    const pool = pools[lang];
    const candidates = rating <= 3 ? pool.mixed : [...pool[kind], ...pool[kind], ...pool.saju].filter(Boolean);
    const fresh = candidates.filter(c => !used.has(c[0]));
    if (!fresh.length) continue;
    const [title, body] = pick(fresh);
    used.add(title);
    // One review per traveller per studio.
    const guests = travellers.filter(t => t[3] === lang && !reviewed.has(t));
    if (!guests.length) continue;
    const guest = pick(guests);
    reviewed.add(guest);
    const visit = new Date(start + rand() * (end - start));
    const created = new Date(visit.getTime() + int(1, 4) * 86400000 + int(8, 22) * 3600000);
    const service = pick(s.services.map(k => services[k][6].en));
    const fill = x => x.replaceAll('{reader}', reader).replaceAll('{area}', s.area);
    w(`insert into public.studio_reviews (studio_id,service_id,reviewer_user_id,reviewer_display_name,reviewer_country_code,language_code,rating,title,body,status,is_mock,verified_booking,visit_date,created_at,updated_at) values (${id},(select id from public.studio_services where studio_id=${id} and name=${q(service)}),(select id from public.profiles where is_mock and display_name=${q(travellerName(guest))}),${q(travellerName(guest))},${q(guest[2])},${q(lang)},${rating},${q(fill(title))},${q(fill(body))},'published',true,false,${q(visit.toISOString().slice(0, 10))},${q(created.toISOString())},${q(created.toISOString())});`);
    reviewTotal++;
  }
}

// 6. Availability for the next three weeks, from each studio's hours. Roughly 1 in 4 slots is already taken.
w(`
-- 6. Availability slots (next 21 days, Asia/Seoul)
insert into public.studio_availability_slots (studio_id,service_id,practitioner_id,starts_at,ends_at,capacity,remaining_capacity,status,is_mock)
select sv.studio_id, sv.id, sv.practitioner_id, st, st + make_interval(mins => sv.duration_minutes), sv.max_guests,
  case when r < 22 then 0 else sv.max_guests end,
  case when r < 22 then 'booked' when r < 27 then 'blocked' else 'available' end, true
from public.studio_services sv
join public.saju_studios s on s.id = sv.studio_id and s.is_mock
cross join generate_series(1, 21) d
join public.studio_hours h on h.studio_id = sv.studio_id and not h.is_closed
  and h.day_of_week = extract(dow from (now() at time zone 'Asia/Seoul')::date + d)
cross join lateral generate_series(
  (((now() at time zone 'Asia/Seoul')::date + d) + h.opens_at + make_interval(mins => 30 * (sv.sort_order % 3))) at time zone 'Asia/Seoul',
  (((now() at time zone 'Asia/Seoul')::date + d) + h.closes_at - make_interval(mins => sv.duration_minutes)) at time zone 'Asia/Seoul',
  interval '2 hours') st
cross join lateral (select abs(hashtext(sv.id::text || st::text)) % 100 as r) x;

-- 7. Keep the denormalised rating fields in step with the (mock) reviews.
update public.saju_studios s set average_rating = x.avg_rating, review_count = x.n, updated_at = now()
from (select studio_id, round(avg(rating)::numeric, 2) as avg_rating, count(*) n from public.studio_reviews where status = 'published' group by studio_id) x
where x.studio_id = s.id and s.is_mock;

commit;
`);

writeFileSync(new URL('../supabase/seed/mock_marketplace.sql', import.meta.url), out.join('\n'));
console.log(`studios=${studios.length} kept=${keep.length} travellers=${travellers.length} reviews=${reviewTotal}`);
