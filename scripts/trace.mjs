// Requirements traceability: checks that every acceptance criterion and quality goal in
// requirements/requirements.json is referenced by at least one check, and writes docs/traceability.md.
//   npm run trace          # write the matrix, fail if anything is untested
//   npm run trace -- --check   # fail only, don't write
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const registry = JSON.parse(readFileSync(join(root, 'requirements/requirements.json'), 'utf8'));
const SCAN = ['src', 'api', 'scripts', 'supabase/tests'];
const TAG = /\[((?:AC-\d{2}[a-z])|(?:QA-\d{2}))\]/g;

export function collectReferences(dirs = SCAN) {
  const refs = new Map();
  const walk = dir => {
    let entries = [];
    try { entries = readdirSync(dir); } catch { return; }
    for (const name of entries) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) { if (name !== 'node_modules') walk(path); continue; }
      if (!/\.(ts|tsx|mjs|js|sql)$/.test(name) || path.endsWith('trace.mjs')) continue;
      const text = readFileSync(path, 'utf8');
      for (const m of text.matchAll(TAG)) {
        const list = refs.get(m[1]) || new Set();
        list.add(relative(root, path));
        refs.set(m[1], list);
      }
    }
  };
  for (const d of dirs) walk(join(root, d));
  return refs;
}

const kind = file => file.endsWith('.test.ts') ? 'unit' : file.includes('responsive-layout-check') ? 'e2e' : file.endsWith('.sql') ? 'db' : file.includes('eval-') ? 'eval' : 'code';
const refs = collectReferences();
const missing = [];
const rows = [];
for (const req of registry.requirements) {
  for (const ac of req.criteria) {
    const files = [...(refs.get(ac.id) || [])].filter(f => kind(f) !== 'code');
    if (!files.length) missing.push(ac.id);
    rows.push(`| ${req.id} | ${req.behavior} | ${req.design.join(', ')} | ${ac.id} | ${ac.text} | ${files.map(f => `\`${f}\` (${kind(f)})`).join('<br>') || '**missing**'} |`);
  }
}
const qaRows = registry.quality.map(q => {
  const files = [...(refs.get(q.id) || [])];
  if (!files.length) missing.push(q.id);
  return `| ${q.id} | ${q.title} | ${q.target} | ${q.measure} | ${files.map(f => `\`${f}\``).join('<br>') || '**missing**'} |`;
});

if (!process.argv.includes('--check')) {
  mkdirSync(join(root, 'docs'), { recursive: true });
  writeFileSync(join(root, 'docs/traceability.md'), `# Requirements traceability

Generated by \`npm run trace\` from \`requirements/requirements.json\` and the \`[AC-xx]\` / \`[QA-xx]\` tags in tests. Do not edit by hand.

| Requirement | Behavior | Design | Criterion | Acceptance criterion | Verified by |
|---|---|---|---|---|---|
${rows.join('\n')}

## Quality goals

| ID | Goal | Target | How it is measured | Referenced in |
|---|---|---|---|---|
${qaRows.join('\n')}
`);
}
if (missing.length) {
  console.error(`Untested criteria: ${missing.join(', ')}`);
  process.exit(1);
}
console.log(`Traceability OK: ${rows.length} acceptance criteria, ${qaRows.length} quality goals, all verified.`);
